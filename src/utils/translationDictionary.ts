/**
 * Translates a given text or sentence into Hindi if in Hindi mode.
 * Performs accurate full dictionary lookup and pattern translation.
 */
export function translateTextToHindi(text: string | null | undefined): string {
  if (!text) return '';
  const trimmed = text.trim();
  if (contentDictionaryHi[trimmed]) {
    return contentDictionaryHi[trimmed];
  }

  // Duration patterns (e.g. "1.5 to 2 Hours", "2 Hours", "3 Days")
  let translated = trimmed;
  if (/^(\d+(\.\d+)?)\s*to\s*(\d+(\.\d+)?)\s*Hours?$/i.test(trimmed)) {
    return trimmed.replace(/(\d+(\.\d+)?)\s*to\s*(\d+(\.\d+)?)\s*Hours?/i, '$1 से $3 घंटे');
  }
  if (/^(\d+(\.\d+)?)\s*Hours?$/i.test(trimmed)) {
    return trimmed.replace(/(\d+(\.\d+)?)\s*Hours?/i, '$1 घंटे');
  }
  if (/^(\d+)\s*Nights?\s*\/\s*(\d+)\s*Days?$/i.test(trimmed)) {
    return trimmed.replace(/(\d+)\s*Nights?\s*\/\s*(\d+)\s*Days?/i, '$1 रातें / $2 दिन');
  }
  if (/^(\d+)\s*Days?$/i.test(trimmed)) {
    return trimmed.replace(/(\d+)\s*Days?/i, '$1 दिन');
  }
  if (/^Day\s*(\d+)$/i.test(trimmed)) {
    return trimmed.replace(/Day\s*(\d+)/i, 'दिन $1');
  }

  return trimmed;
}

